SELECT
    LI.ORDERKEY,
    LI.LINENUMBER,
    LI.PARTKEY,
    LI.SUPPKEY,
    LI.QUANTITY,
    LI.EXTENDEDPRICE,
    LI.DISCOUNT,
    LI.TAX,
    LI.RETURNFLAG,
    LI.LINESTATUS,
    LI.SHIPDATE,
    LI.COMMITDATE,
    LI.RECEIPTDATE,
    LI.SHIPINSTRUCT,
    LI.SHIPMODE,
    S.SUPPLIERNAME,
    S.ADDRESS AS SUPPLIER_ADDRESS,
    S.PHONE AS SUPPLIER_PHONE,
    P.NAME AS PART_NAME,
    P.PARTKEY AS PART_KEY,
    P.MFGR AS PART_MFGR,
    P.BRAND AS PART_BRAND,
    P.TYPE AS PART_TYPE,
    P.SIZE AS PART_SIZE,
    P.CONTAINER AS PART_CONTAINER,
    P.RETAILPRICE AS PART_RETAILPRICE,
    C.CUSTOMER_NAME AS CUSTOMER_NAME,
    C.ADDRESS AS ADDRESS,
    C.PHONE AS PHONE,
    CURRENT_TIMESTAMP AS LOAD_TIMESTAMP
FROM {{ ref('DIM_LINEITEM') }} LI
LEFT JOIN {{ ref('DIM_SUPPLIER') }} S ON LI.SUPPKEY = S.SUPPLIERKEY
LEFT JOIN {{ ref('DIM_PART') }} P ON LI.PARTKEY = P.PARTKEY
LEFT JOIN {{ ref('DIM_CUSTOMER') }} C ON LI.SUPPKEY = C.CUSTKEY
